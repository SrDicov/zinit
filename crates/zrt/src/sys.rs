/// How a child terminated.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum ExitStatus {
    /// `exit(n)` / return from `main`. `n` is the low 8 bits of the status.
    Exited(i32),
    /// Killed by a signal, with or without a core dump.
    Signaled {
        /// The signal number that killed it, e.g. 9 for `SIGKILL`.
        signal: i32,
        /// Whether the kernel also wrote a core file.
        core_dumped: bool,
    },
    /// Stopped or continued, reported by a `WUNTRACED` `waitpid`.
    ///
    /// zinit never uses `WUNTRACED`; a supervisor that traced its children
    /// would stop supervising them. The variant exists so that a surprising
    /// status word is representable instead of being silently mis-decoded.
    Reported(i32),
}

impl ExitStatus {
    /// True only for `exit(0)`. A signal death is never "success", even
    /// `SIGTERM` — the service did not choose to stop.
    pub fn is_success(self) -> bool {
        matches!(self, ExitStatus::Exited(0))
    }

    /// The number to report to the operator and to `zcore`.
    ///
    /// A signalled child reports `128 + signal`, the shell convention, because
    /// every log format, every monitoring system and every human already knows
    /// it. `Exited(0)` reports 0.
    pub fn code(self) -> i32 {
        match self {
            ExitStatus::Exited(c) => c,
            ExitStatus::Signaled { signal, .. } => 128 + signal,
            ExitStatus::Reported(c) => c,
        }
    }
}

/// One completed `waitpid`.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Waited {
    /// The child that changed state. Useful with `waitpid(-1, ...)`.
    pub pid: i32,
    /// How it terminated.
    pub status: ExitStatus,
}

/// Decode a raw `wait(2)` status word.
///
/// Split out because the encoding is a bit-packed kernel ABI and getting the
/// order of the tests wrong is the classic bug (`WIFSIGNALED` before
/// `WIFEXITED` inverts the meaning of everything).
pub fn decode_status(raw: i32) -> ExitStatus {
    // These are `const fn`s in libc, pure bit operations on the status word.
    // The order of the tests is the whole point: checking `WIFSIGNALED` before
    // `WIFEXITED` inverts the meaning of every status, which is the single
    // most common bug in hand-rolled `wait(2)` decoders.
    if libc::WIFEXITED(raw) {
        ExitStatus::Exited(libc::WEXITSTATUS(raw))
    } else if libc::WIFSIGNALED(raw) {
        ExitStatus::Signaled {
            signal: libc::WTERMSIG(raw),
            core_dumped: libc::WCOREDUMP(raw),
        }
    } else {
        ExitStatus::Reported(raw)
    }
}

/// `waitpid(pid, WNOHANG)` for one child, or for any child if `pid` is `-1`.
///
/// `Ok(None)` is the normal, expected answer: "nothing has changed yet". The
/// distinction matters because an init calls this in a loop and must be able to
/// tell "no child died" from "the kernel is broken".
pub fn waitpid_nohang(pid: i32) -> io::Result<Option<Waited>> {
    loop {
        let mut status: libc::c_int = 0;
        // SAFETY: `&raw mut status` is a live, aligned `c_int`; `waitpid`
        // writes exactly one there. `pid == -1` and `0` have their documented
        // POSIX meanings ("any child", "any child in my group").
        let rc = unsafe { libc::waitpid(pid, &raw mut status, libc::WNOHANG) };
        if rc > 0 {
            return Ok(Some(Waited {
                pid: rc,
                status: decode_status(status),
            }));
        }
        if rc == 0 {
            return Ok(None);
        }
        let err = io::Error::last_os_error();
        // `ECHILD` means there is no such child: it exited and was already
        // reaped, or it was never ours. Not an error for a reaper.
        if err.raw_os_error() == Some(libc::ECHILD) {
            return Ok(None);
        }
        if err.kind() != io::ErrorKind::Interrupted {
            return Err(err);
        }
        // EINTR: a signal arrived between the check and the call. Retry.
    }
}

/// `waitpid(pid, 0)` — block until the child changes state.
///
/// Retries `EINTR` internally, which is the entire reason this function
/// exists: a supervisor has `SIGCHLD` blocked and reaps from the event loop, so
/// a raw `waitpid` interrupted by an unrelated signal would otherwise surface
/// as a spurious error.
pub fn waitpid_blocking(pid: i32) -> io::Result<Waited> {
    loop {
        let mut status: libc::c_int = 0;
        // SAFETY: as `waitpid_nohang`, but without WNOHANG.
        let rc = unsafe { libc::waitpid(pid, &raw mut status, 0) };
        if rc > 0 {
            return Ok(Waited {
                pid: rc,
                status: decode_status(status),
            });
        }
        let err = io::Error::last_os_error();
        if err.kind() != io::ErrorKind::Interrupted {
            return Err(err);
        }
    }
}

