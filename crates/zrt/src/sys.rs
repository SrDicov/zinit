/// `open(2)` with `O_CLOEXEC` always set.
///
/// There is no way to get a non-CLOEXEC fd from this module on purpose. The
/// only descriptors that must survive an exec are the ones stdio and the
/// control protocol hold, and those are duplicated with `dup2` by the spawn
/// path.
pub fn open_cloexec(path: &Path, flags: i32, mode: u32) -> io::Result<RawFd> {
    openat_nofollow(libc::AT_FDCWD, path, flags, mode)
}

/// `openat(2)` with `O_NOFOLLOW` and `O_CLOEXEC` always set.
///
/// `O_NOFOLLOW` because the supervisor's whole security argument rests on not
/// being tricked by a symlink at a path it is about to chown, chmod or mount
/// (`DESIGN.md` §9 rule 4). `O_CLOEXEC` for the leak reason in [`pipe2`].
///
/// Pass `AT_FDCWD` as `dirfd` for an absolute path; this exists so a caller
/// can open relative to a directory fd it already holds, which closes the
/// TOCTOU window that `open(path)` + `fchown(path)` leaves open.
pub fn openat_nofollow(dirfd: RawFd, path: &Path, flags: i32, mode: u32) -> io::Result<RawFd> {
    let c = cpath(path)?;
    let flags = flags | libc::O_NOFOLLOW | libc::O_CLOEXEC;
    // SAFETY: `c` is a NUL-terminated string alive for this call, `dirfd` is
    // either AT_FDCWD or a real descriptor the caller owns, and `mode` is only
    // consulted when O_CREAT is set. The kernel copies the path; it does not
    // retain the pointer.
    let fd = unsafe { libc::openat(dirfd, c.as_ptr(), flags, mode as libc::c_uint) };
    if fd < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(fd)
    }
}

/// `rename(2)`: atomic replace.
///
/// This is how a service's state file is published, and why it is `rename` and
/// not "write, then rename the temp": a reader either sees the whole old file
/// or the whole new one.
pub fn rename(from: &Path, to: &Path) -> io::Result<()> {
    let a = cpath(from)?;
    let b = cpath(to)?;
    // SAFETY: two NUL-terminated paths, both alive for the call.
    if unsafe { libc::rename(a.as_ptr(), b.as_ptr()) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

