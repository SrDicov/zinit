/// `Path` → `CString`, refusing an interior NUL.
///
/// Every path-taking wrapper funnels through this so that no wrapper can ever
/// hand the kernel a truncated path — the failure mode where
/// `/run/zinit.sock` becomes `/run/zinit` and the init quietly serves the
/// wrong socket.
fn cpath(p: &Path) -> io::Result<CString> {
    CString::new(p.as_os_str().as_bytes()).map_err(|_| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("path contains an interior NUL: {}", p.display()),
        )
    })
}

fn cstr(s: &str) -> io::Result<CString> {
    CString::new(s).map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "interior NUL"))
}

use core::mem::{align_of, size_of};

const fn len_of<T>() -> usize {
    size_of::<T>()
}

/// `sizeof(T)`, kept as a named function so the control-message arithmetic
/// below reads as layout rather than as a pile of `size_of` calls.
const fn hdr_size_of<T>() -> usize {
    size_of::<T>()
}

/// Round a length up to the control buffer's alignment.
///
/// POSIX requires control data to begin at an `size_t`-aligned offset even
/// when the header itself is smaller, and several platforms enforce it.
const fn cmsg_align(len: usize) -> usize {
    (len + align_of::<usize>() - 1) & !(align_of::<usize>() - 1)
}
