/// Which clock a [`try_clock_gettime_ms`] call reads.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum ClockId {
    /// `CLOCK_MONOTONIC`: boot-relative, never jumps. Deadlines only.
    Monotonic,
    /// `CLOCK_REALTIME`: wall clock. Human-facing output only.
    Realtime,
}

impl ClockId {
    /// The `clockid_t` this variant maps to.
    const fn raw(self) -> libc::clockid_t {
        match self {
            // `CLOCK_MONOTONIC` has existed on every POSIX platform zinit
            // targets; the runtime probe in `clock::clock_source` is about
            // kernels and containers that lie about it, not about the header.
            ClockId::Monotonic => libc::CLOCK_MONOTONIC,
            ClockId::Realtime => libc::CLOCK_REALTIME,
        }
    }
}

/// `clock_gettime(CLOCK_MONOTONIC|CLOCK_REALTIME)` in milliseconds.
///
/// Nanoseconds are truncated, not rounded: a deadline that fires a hair early
/// is harmless, one that fires a hair late is a bug report. Overflow of the
/// 64-bit millisecond counter is decades away and saturates rather than wraps.
pub fn clock_gettime_ms(id: ClockId) -> u64 {
    match try_clock_gettime_ms(id) {
        Ok(ms) => ms,
        Err(e) => {
            // A failing clock is catastrophic but not a reason to abort PID 1.
            // Returning 0 keeps the supervisor running with a visibly broken
            // clock; the probe that produced this path already logged why.
            crate::report::announce_degradation(&format!("clock_gettime failed: {e}"));
            0
        }
    }
}

/// [`clock_gettime_ms`] with the error preserved, for probes and tests.
pub fn try_clock_gettime_ms(id: ClockId) -> io::Result<u64> {
    let mut ts = libc::timespec {
        tv_sec: 0,
        tv_nsec: 0,
    };
    // SAFETY: `ts` is a live, aligned `timespec` on this frame and
    // `clock_gettime` writes exactly one. It does not retain the pointer.
    if unsafe { libc::clock_gettime(id.raw(), &raw mut ts) } != 0 {
        return Err(io::Error::last_os_error());
    }
    if ts.tv_sec < 0 || ts.tv_nsec < 0 {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "clock_gettime returned a negative time",
        ));
    }
    let ms = (ts.tv_sec as u64)
        .saturating_mul(1000)
        .saturating_add(ts.tv_nsec as u64 / 1_000_000);
    Ok(ms)
}

