/// `fork(2)`.
///
/// Returns `Ok(0)` in the child and `Ok(pid)` in the parent — the same
/// convention as libc, kept deliberately so nobody "fixes" it into an enum and
/// hides which side of the fork they are on.
///
/// # The child side
///
/// Everything after `fork` in a child is restricted to async-signal-safe
/// calls (`DESIGN.md` §9.1). This function is the raw syscall; the safe
/// wrapper with the pre-allocated argv and the single-exit child path is
/// [`crate::childproc::fork_tracked`]. Nothing here allocates.
pub fn fork() -> io::Result<i32> {
    // SAFETY: `fork` takes no arguments and has no preconditions. Its dangers
    // are all on the *child* side (only async-signal-safe calls, no locks held
    // by another thread, no allocator use), and those are obligations on the
    // caller, not on the call itself.
    let pid = unsafe { libc::fork() };
    if pid < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(pid)
    }
}

/// Leave the process without running any destructor, flushing any buffer or
/// running any exit hook.
///
/// The only legal exit for a forked child that could not `exec`. Running
/// `exit` (or unwinding) there would flush stdio buffers a *parent* also owns
/// — a classic double-flush that turns into duplicated log lines.
pub fn _exit(code: i32) -> ! {
    // SAFETY: `_exit` never returns, takes an int, and has no preconditions.
    // Its whole purpose is to be async-signal-safe.
    unsafe { libc::_exit(code) }
}

/// `execvp(3)`: search `PATH` and replace this process.
///
/// # Errors
///
/// On success this does not return — the process image is gone. So the error
/// type is [`core::convert::Infallible`]: a returned `Ok` is unrepresentable
/// and cannot be forgotten by a caller that pattern-matches.
///
/// The child path in a supervisor must be a *single* branch: if `execvp` fails,
/// [`execvp_or_exit`] turns it into `_exit(127)`, the universal "cannot execute"
/// status. There is no other way out of a forked child.
pub fn execvp(file: &CStr, argv: &[&CStr]) -> io::Result<core::convert::Infallible> {
    // The pointers handed to execvp must outlive the call, which they do:
    // `file` and every `argv` element borrow from live `CStr`s, and the
    // pointer array itself is built on the stack of this frame, which is alive
    // for the duration of the call.
    let ptrs: Vec<*const libc::c_char> = argv.iter().map(|a| a.as_ptr()).collect();
    let argv_ptr = if ptrs.is_empty() {
        std::ptr::null()
    } else {
        ptrs.as_ptr()
    };
    // SAFETY: `file` is a NUL-terminated C string by construction of `CStr`,
    // and `argv_ptr` points to a NUL-terminated array of pointers to
    // NUL-terminated strings (`argv` is required to end in a NUL, which the
    // caller must do — see `execvp_or_exit`). `execvp` reads them and does not
    // retain any of them past the call. On success it never returns.
    let _rc = unsafe { libc::execvp(file.as_ptr(), argv_ptr) };
    // Only reached on failure: -1 with errno set.
    Err(io::Error::last_os_error())
}

/// The only sanctioned child path: `execvp`, or die with 127.
///
/// Writing this as one function is the point. A child that fails to `exec`
/// must become an ordinary `Exited(127)` that the reconciler handles like any
/// other failed start — never a silent return into the parent's event loop,
/// which is the bug runit has been copied for having.
///
/// The caller must pass an `argv` whose **last element is a null pointer**
/// (`CStr` cannot hold one, so the terminator is passed separately as
/// `&[]`… see [`exec_argv`]).
pub fn execvp_or_exit(file: &CStr, argv: &[*const libc::c_char]) -> ! {
    if argv.last() == Some(&std::ptr::null()) {
        // SAFETY: the caller guarantees `argv` is a NUL-terminated array of
        // pointers to NUL-terminated strings (built by `exec_argv`), and the
        // array is alive on this frame's stack for the whole call.
        unsafe { libc::execvp(file.as_ptr(), argv.as_ptr()) };
    }
    _exit(127)
}

/// Build the `argv` array `execvp` wants from ordinary `CStr`s.
///
/// Preparing this **before** the fork is one of the three mitigations in
/// `DESIGN.md` §9.1: the child allocates nothing. It also appends the NUL
/// terminator that `CStr` itself cannot express.
pub fn exec_argv(args: &[&CStr]) -> Vec<*const libc::c_char> {
    let mut v: Vec<*const libc::c_char> = args.iter().map(|a| a.as_ptr()).collect();
    v.push(std::ptr::null());
    v
}

/// The current process id.
pub fn getpid() -> i32 {
    // SAFETY: `getpid` has no arguments, no preconditions, and never fails on
    // any POSIX system (it is the one syscall allowed to fail on ancient
    // kernels, and the fallback below keeps that from being a panic).
    let pid = unsafe { libc::getpid() };
    if pid < 0 {
        // Cannot happen; returning 0 is safer than panicking in an init.
        0
    } else {
        pid
    }
}

/// `kill(2)` on a single process.
pub fn kill_process(pid: i32, sig: Signal) -> io::Result<()> {
    // SAFETY: `kill` only inspects a pid and a signal number; there is no
    // pointer to get wrong. Passing pid 0 or -1 would signal a group, which is
    // why the group variant is a separate function: the two are too easy to
    // confuse at a call site.
    if unsafe { libc::kill(pid, sig.as_raw()) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `kill(2)` on a whole process group (negative pid).
///
/// This is how a service tree is stopped. It exists as its own function
/// because sending to `-pid` by accident is how an init kills itself.
pub fn kill_group(pid: i32, sig: Signal) -> io::Result<()> {
    // SAFETY: as above; a negative pid targets a process group.
    if unsafe { libc::kill(-pid, sig.as_raw()) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

