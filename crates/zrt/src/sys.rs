/// `mount(2)`, with the differences between platforms resolved here.
///
/// This is the ugliest signature in the crate, and that is the point of
/// having it: `mount(2)` takes five arguments on Linux (with a *filesystem
/// type*) and four on the BSDs (which infer the type from the mount helper
/// being used), and NetBSD adds a sixth. Rather than pushing a `#[cfg]` onto
/// every caller — there will be exactly one, in the tmpfs stage — the shape
/// difference is absorbed here and the *semantic* difference is documented:
///
/// * Linux needs `fstype` ("tmpfs"); the BSDs ignore it and take the type
///   from the `data` string instead. Passing `None` on a BSD is legal.
/// * The BSD flag values are `c_int`, Linux's are `c_ulong`, so they are
///   taken as `u32` and cast.
pub fn mount(
    source: Option<&Path>,
    target: &Path,
    fstype: Option<&str>,
    flags: u32,
    data: Option<&str>,
) -> io::Result<()> {
    let src = match source {
        Some(p) => Some(cpath(p)?),
        None => None,
    };
    let typ = match fstype {
        Some(s) => Some(cstr(s)?),
        None => None,
    };
    let dat = match data {
        Some(s) => Some(cstr(s)?),
        None => None,
    };
    let target_c = cpath(target)?;
    let src_ptr = src.as_ref().map_or(std::ptr::null(), |c| c.as_ptr());
    let typ_ptr = typ.as_ref().map_or(std::ptr::null(), |c| c.as_ptr());
    // The BSD `mount(2)` takes `data` as a mutable pointer (it is a varargs
    // buffer the kernel may read back into on some systems), Linux as a const
    // one. Both are reached from this one expression, produced as `*mut` and
    // cast back down to `*const` on the Linux branch. The pointee is a
    // `CString` that outlives the call either way, and the kernel does not
    // write through it on any platform zinit supports — hence `*const` on the
    // only branch where the compiler will accept it.
    // Produced as `*mut` because the BSD `mount(2)` declares it that way; the
    // pointed-to bytes are never written (see the safety note at the call).
    let dat_ptr: *mut libc::c_void = match &dat {
        Some(c) => c.as_ptr().cast_mut().cast::<libc::c_void>(),
        None => std::ptr::null_mut(),
    };

    // Every branch below produces an `io::Result<()>` directly, rather than a
    // raw `c_int` that is inspected afterwards. That is what lets the
    // unsupported-platform branch exist at all: there is no `c_int` to return
    // from a platform where `mount(2)` was never declared.

    // SAFETY: every pointer is either null (which `mount(2)` accepts as "none"
    // for the source and, on the BSDs, for the type) or a NUL-terminated
    // string held by a `CString` in this frame for the whole call. The
    // pointers are not retained.
    #[cfg(any(target_os = "linux", target_os = "android"))]
    let rc = unsafe {
        libc::mount(
            src_ptr,
            target_c.as_ptr(),
            typ_ptr,
            flags as libc::c_ulong,
            dat_ptr.cast_const(),
        )
    };
    #[cfg(any(target_os = "linux", target_os = "android"))]
    let out = if rc == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    };

    // SAFETY: as above. Four arguments: the BSD `mount(2)` infers the
    // filesystem type from `data`, so `typ_ptr` is not passed and the
    // `fstype` argument this function takes is ignored on these platforms.
    #[cfg(any(
        target_os = "macos",
        target_os = "ios",
        target_os = "tvos",
        target_os = "watchos",
        target_os = "visionos",
        target_os = "freebsd",
        target_os = "openbsd",
        target_os = "dragonfly",
    ))]
    let out = {
        let _ = typ_ptr;
        // SAFETY: as above.
        let rc = unsafe { libc::mount(src_ptr, target_c.as_ptr(), flags as libc::c_int, dat_ptr) };
        if rc == 0 {
            Ok(())
        } else {
            Err(io::Error::last_os_error())
        }
    };

    // SAFETY: as above. NetBSD appends a `size` argument for the extensible
    // attributes buffer, which zinit never uses, so it passes 0.
    #[cfg(target_os = "netbsd")]
    let out = {
        let _ = typ_ptr;
        // SAFETY: as above.
        let rc =
            unsafe { libc::mount(src_ptr, target_c.as_ptr(), flags as libc::c_int, dat_ptr, 0) };
        if rc == 0 {
            Ok(())
        } else {
            Err(io::Error::last_os_error())
        }
    };

    // No `mount(2)` declaration for this target. Reported, not faked: a
    // supervisor that silently skipped the tmpfs stage would then fail later
    // on a missing `/run`, far from the cause.
    #[cfg(not(any(
        target_os = "linux",
        target_os = "android",
        target_os = "macos",
        target_os = "ios",
        target_os = "tvos",
        target_os = "watchos",
        target_os = "visionos",
        target_os = "freebsd",
        target_os = "openbsd",
        target_os = "netbsd",
        target_os = "dragonfly",
    )))]
    let out: io::Result<()> = {
        let _ = (src_ptr, typ_ptr, dat_ptr, target_c);
        Err(io::Error::new(
            io::ErrorKind::Unsupported,
            "mount(2) is not wrapped for this platform",
        ))
    };

    out
}

/// `umount2(2)` on Linux, `unmount(2)` on the BSDs, with the same `u32` flags.
///
/// The two are the same call with different names and different flag types
/// (`MNT_FORCE` on the BSDs, `MNT_DETACH` semantics of its own on Linux). The
/// caller passes a `u32` and this picks the right spelling.
pub fn umount2(target: &Path, flags: u32) -> io::Result<()> {
    let t = cpath(target)?;

    // SAFETY: a NUL-terminated path alive for the call and an int flag.
    #[cfg(any(target_os = "linux", target_os = "android"))]
    let rc = unsafe { libc::umount2(t.as_ptr(), flags as libc::c_int) };

    // SAFETY: as above. `unmount(2)` is the BSD spelling of the same syscall;
    // it returns -1 with errno on failure like every other libc call.
    #[cfg(any(
        target_os = "macos",
        target_os = "ios",
        target_os = "tvos",
        target_os = "watchos",
        target_os = "visionos",
        target_os = "freebsd",
        target_os = "openbsd",
        target_os = "netbsd",
        target_os = "dragonfly",
    ))]
    let rc = unsafe { libc::unmount(t.as_ptr(), flags as libc::c_int) };

    #[cfg(not(any(
        target_os = "linux",
        target_os = "android",
        target_os = "macos",
        target_os = "ios",
        target_os = "tvos",
        target_os = "watchos",
        target_os = "visionos",
        target_os = "freebsd",
        target_os = "openbsd",
        target_os = "netbsd",
        target_os = "dragonfly",
    )))]
    let rc: libc::c_int = {
        let _ = (t, flags);
        -1
    };

    if rc == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `sethostname(2)`.
///
/// The length argument is `c_int` on Apple and the BSDs and `size_t` on
/// Linux and NetBSD, which is why it goes in as `as _`: the cast is resolved
/// against whatever the field's type is on the target being compiled, and
/// there is no `cfg` to get wrong.
pub fn sethostname(name: &str) -> io::Result<()> {
    let bytes = name.as_bytes();
    if bytes.contains(&0) {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "hostname contains an interior NUL",
        ));
    }
    // SAFETY: `bytes` is a live slice for the whole call; `sethostname` copies
    // exactly `len` bytes and does not retain the pointer. The length is cast
    // to the parameter type this platform declares.
    if unsafe { libc::sethostname(bytes.as_ptr().cast::<libc::c_char>(), bytes.len() as _) } != 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(())
    }
}

// `TIOCGSID` and `TIOCSCTTY` are ioctl *request numbers*, and they are not
// exported by the `libc` crate on every platform that has them. They are also
// not guessable: each is an `_IO`/`_IOR` encoding whose value depends on the
// group letter, the command number and the argument size. Rather than
// hardcode a table that would silently be wrong somewhere, the ones that are
// missing are declared here from the platform's own headers, and the ones
// that `libc` does export are used directly.
#[cfg(any(target_os = "linux", target_os = "android"))]
#[allow(clippy::unnecessary_cast)] // same-type on 32-bit, load-bearing elsewhere
const TIOCGSID_REQ: u32 = libc::TIOCGSID as u32;
#[cfg(any(target_os = "freebsd", target_os = "dragonfly", target_os = "openbsd",))]
#[allow(clippy::unnecessary_cast)] // same-type on 32-bit, load-bearing elsewhere
const TIOCGSID_REQ: u32 = libc::TIOCGSID as u32;
// `_IOR('t', 124, int)`: IOC_OUT | (sizeof(int) << 16) | ('t' << 8) | 124.
#[cfg(target_os = "netbsd")]
const TIOCGSID_REQ: u32 = 0x4004_747c;
// macOS removed `TIOCGSID` from <sys/ttycom.h>; Darwin's answer is
// `TIOCGPGRP` (which returns the foreground *process group*, not the session),
// so this call cannot be answered on Darwin and says so.
#[cfg(target_vendor = "apple")]
const TIOCGSID_REQ: u32 = 0;

//
// They are stored as `u64` and cast with `as _` at the `ioctl` call, because
// the request parameter's type is not stable across libc targets: it is
// `c_ulong` under glibc and `c_int` under musl. `as _` makes the cast resolve
// against whatever the function being called declares, so there is no
// platform to get wrong.
// The `as u64` is a no-op on glibc (where `TIOCSCTTY` is already `c_ulong =
// u64`) and load-bearing on musl (where it is `c_int = i32`). Clippy only sees
// the target it is compiling for, so the cast is kept and the lint that
// objects to it on one target is silenced with the reason, rather than the
// code being bent to satisfy whichever target happens to be the host.
#[allow(clippy::unnecessary_cast)]
#[cfg(any(
    target_os = "linux",
    target_os = "android",
    target_os = "freebsd",
    target_os = "dragonfly",
))]
const TIOCSCTTY_REQ: u64 = libc::TIOCSCTTY as u64;
// NetBSD and OpenBSD both spell it `_IO('t', 97)` = IOC_VOID | ('t' << 8) | 97.
#[cfg(any(target_os = "netbsd", target_os = "openbsd"))]
const TIOCSCTTY_REQ: u64 = 0x2000_7461;
// Darwin's <sys/ttycom.h> defines `TIOCSCTTY` as `_IO('t', 97)` =
// IOC_VOID | ('t' << 8) | 97.
#[cfg(target_vendor = "apple")]
const TIOCSCTTY_REQ: u64 = 0x2000_7461;

/// `tcgetsid(2)`: the session id owning this terminal.
///
/// A non-blocking readiness read on a console: it returns `EIO` when there is
/// no session attached yet, which is the normal answer for a tty nobody has
/// logged into.
///
/// # Darwin
///
/// Not available. macOS removed `TIOCGSID` and offers only `TIOCGPGRP`,
/// which answers a different question (the foreground process group, not the
/// session). Rather than return the process group and call it a session — a
/// bug that only shows up as a console service that will not stop — this
/// returns `ENOSYS`, and the console code in `zservice` has an explicit
/// branch for it.
#[cfg(target_vendor = "apple")]
pub fn tcgetsid(fd: RawFd) -> io::Result<i32> {
    let _ = fd;
    Err(io::Error::from_raw_os_error(libc::ENOSYS))
}

/// `tcgetsid(2)`: the session id owning this terminal.
///
/// A non-blocking readiness read on a console: it returns `EIO` when there is
/// no session attached yet, which is the normal answer for a tty nobody has
/// logged into.
#[cfg(not(target_vendor = "apple"))]
pub fn tcgetsid(fd: RawFd) -> io::Result<i32> {
    tcgetioctl_int(fd, TIOCGSID_REQ)
}

fn tcgetioctl_int(fd: RawFd, request: u32) -> io::Result<i32> {
    let mut out: libc::c_int = 0;
    // SAFETY: the request writes exactly one `c_int` through the pointer, and
    // `out` is a live, aligned local. The request number is the platform's own
    // `TIOCGSID` constant.
    if unsafe { libc::ioctl(fd, request as _, &raw mut out) } == 0 {
        Ok(out)
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `ioctl(TIOCSCTTY)` — make this terminal the process's controlling terminal.
///
/// Linux's `TIOCSCTTY` takes the steal flag as its argument; the BSDs take
/// none, so the argument is `0` there. The caller must already be a session
/// leader (it has called `setsid(2)`); otherwise the call fails with `ENOTTY`,
/// which is the kernel telling the truth about the ordering.
pub fn ioctl_tiocsctty(fd: RawFd, steal: bool) -> io::Result<()> {
    #[cfg(any(target_os = "linux", target_os = "android"))]
    let arg: libc::c_ulong = if steal { 1 } else { 0 };
    #[cfg(not(any(target_os = "linux", target_os = "android")))]
    let arg: libc::c_ulong = 0;
    #[cfg(not(any(target_os = "linux", target_os = "android")))]
    let _ = steal;
    // SAFETY: the argument is a single unsigned long, which is what the
    // BSDs' `TIOCSCTTY` (no argument) and Linux's (steal flag) both expect,
    // and the request number is the platform's own constant.
    if unsafe { libc::ioctl(fd, TIOCSCTTY_REQ as _, arg) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

