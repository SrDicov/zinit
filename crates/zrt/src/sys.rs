/// `prctl(PR_SET_NO_NEW_PRIVS, 1)` — forbid gaining privilege via exec.
///
/// Linux only, and the single most valuable line in the whole drop sequence:
/// after it, a setuid binary a service execs cannot raise that service's
/// privilege. Not a substitute for the uid change, but it makes a mistake in
/// the uid change non-exploitable.
#[cfg(any(target_os = "linux", target_os = "android"))]
pub fn set_no_new_privs() -> io::Result<()> {
    // SAFETY: prctl with PR_SET_NO_NEW_PRIVS takes two int-like arguments;
    // the constant and the value are both compile-time.
    if unsafe { libc::prctl(libc::PR_SET_NO_NEW_PRIVS, 1, 0, 0, 0) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `PER_LINUX`, from `linux/personality.h`.
///
/// Not re-exported by the `libc` crate, and hand-written rather than copied
/// from a header at build time: this crate has no build script and no
/// `pkg-config`, and one more `const` is a smaller price than either.
#[cfg(any(target_os = "linux", target_os = "android"))]
const PER_LINUX: libc::c_ulong = 0x0000;

/// `personality(ADDR_NO_RANDOMIZE | PER_LINUX)` — disable ASLR for a service.
///
/// Linux only. Queried rather than set on purpose: this is a probe, and a
/// probe must have no side effects. An invalid persona (`0xffff_ffff`) makes
/// the kernel answer with the current value and change nothing.
#[cfg(any(target_os = "linux", target_os = "android"))]
pub fn query_personality() -> io::Result<u32> {
    // SAFETY: `personality` takes and returns a persona bitmask; the invalid
    // value is documented to be a pure query that changes nothing.
    let rc = unsafe { libc::personality(!0u32 as libc::c_ulong) };
    if rc == -1 {
        // The kernel answers -1/EINVAL for an unknown persona, so `EINVAL`
        // means "the call exists" and anything else is a real failure.
        let e = io::Error::last_os_error();
        if e.raw_os_error() == Some(libc::EINVAL) {
            return Ok(0);
        }
        return Err(e);
    }
    Ok(rc as u32)
}

/// `personality(PER_LINUX | ADDR_NO_RANDOMIZE)`. Linux only.
#[cfg(any(target_os = "linux", target_os = "android"))]
pub fn set_addr_no_randomize() -> io::Result<()> {
    let want = PER_LINUX | libc::ADDR_NO_RANDOMIZE as libc::c_ulong;
    // SAFETY: one ulong; the kernel validates the persona and returns the
    // previous one.
    if unsafe { libc::personality(want) } == -1 {
        return Err(io::Error::last_os_error());
    }
    Ok(())
}

/// `pidfd_open(2)`: an fd that becomes readable when that exact process dies.
///
/// Linux 5.3+. The value of this call is not "an event when a pid exits" —
///
/// that is what `SIGCHLD` already does — but that the fd refers to *one
/// specific process*. A pid can be recycled the instant it dies; a pidfd
/// cannot. An init that learns "child 1234 died" and then looks up 1234 in a
/// table has a race, and the pidfd backend closes it.
///
/// Routed through `syscall(2)` rather than the libc wrapper because glibc only
/// grew the wrapper in 2.36, and zinit has to run on the glibc of whatever
/// distribution booted it.
#[cfg(any(target_os = "linux", target_os = "android"))]
pub fn pidfd_open(pid: i32) -> io::Result<RawFd> {
    // SAFETY: variadic `syscall` with two integer arguments passed as
    // `c_long`, which is what the kernel's `sys_pidfd_open(pid, flags)`
    // prototype expects. The return value is an fd or -1 with errno set.
    // (x32 is excluded from the capabilities probe for the same reason: a
    // variadic pointer/argument width mismatch. This call passes no
    // pointers, so it is safe there too.)
    let rc = unsafe { libc::syscall(libc::SYS_pidfd_open, pid as libc::c_long, 0 as libc::c_long) };
    if rc < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(rc as RawFd)
    }
}

