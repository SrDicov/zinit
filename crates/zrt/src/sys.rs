/// `Path` → `CString`, refusing an interior NUL.
///
/// Every path-taking wrapper funnels through this so that no wrapper can ever
/// hand the kernel a truncated path — the failure mode where
/// `/run/zinit.sock` becomes `/run/zinit` and the init quietly serves the
/// wrong socket.
fn cpath(p: &Path) -> io::Result<CString> {
    CString::new(p.as_os_str().as_bytes()).map_err(|_| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("path contains an interior NUL: {}", p.display()),
        )
    })
}

fn cstr(s: &str) -> io::Result<CString> {
    CString::new(s).map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "interior NUL"))
}
