//! Every syscall the rest of `zrt` is allowed to call.
//!
//! # The rules of this module
//!
//! * **One function per syscall.** Not per *concept*. There is a
//!   `dup2` because the supervisor redirects stdio and a `dup2_cloexec`
//!   because it hands fds to children; mixing them into a generic `dup` with a
//!   bool parameter is how an `FD_CLOEXEC` bug reaches production.
//! * **Every function returns `io::Result`.** The errno is the message. A
//!   `Result` is the only way an init can survive a failing syscall, and a
//!   `panic!` here would take down PID 1 and restart the whole supervisor.
//! * **Every `unsafe` block carries a `// SAFETY:` comment saying why the
//!   precondition holds.** The comment is the review surface. A binding
//!   generated by a macro cannot carry it, which is why this crate has exactly
//!   one dependency and hand-writes its FFI.
//! * **Interruptions are handled here, not by callers.** `EINTR` on
//!   `waitpid`, `accept`, `read` and `nanosleep` is normal in a process that
//!   receives signals as often as an init does. It is retried inside the
//!   wrapper so that no caller can forget.
//!
//! # What is deliberately absent
//!
//! Nothing that `std` already does correctly. `read`/`write` below are the
//! only overlap, and they exist because this crate is deliberately
//! fd-centric: descriptors are the vocabulary the reactor, the signal source
//! and the child tracker all speak, and `std::fs::File` is a second,
//! incompatible one. What `std` does *not* have is everything with
//! out-of-line arguments or platform-varying constants, and that is the bulk
//! of this file.

use core::ffi::CStr;
use std::ffi::{CString, OsStr};
use std::io;
use std::os::fd::RawFd;
use std::os::unix::ffi::OsStrExt;
use std::path::{Component, Path, PathBuf};

use crate::signals::Signal;

