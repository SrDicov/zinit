/// `close(2)`.
///
/// `EBADF` is a *bug indicator*, not a runtime condition, so it is reported
/// rather than swallowed — but it is also the single most likely benign
/// outcome when a child has already closed the fd, which is why
/// [`close_quietly`] exists.
pub fn close(fd: RawFd) -> io::Result<()> {
    // SAFETY: `close` takes an int; closing an invalid fd is an error return,
    // not undefined behaviour.
    if unsafe { libc::close(fd) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `close(2)` that maps `EBADF` to success.
///
/// Only for cleanup paths where the fd may legitimately be gone (a child that
/// died mid-setup, a double close in an error path).
pub fn close_quietly(fd: RawFd) -> io::Result<()> {
    match close(fd) {
        Err(e) if e.raw_os_error() == Some(libc::EBADF) => Ok(()),
        other => other,
    }
}

/// `dup2(2)`: make `newfd` refer to the same open file description as `oldfd`.
///
/// The one deliberate exception to the `FD_CLOEXEC` rule in this module: stdio
/// redirection happens *after* the CLOEXEC decision for the child, and the
/// target (0, 1, 2) must survive the exec.
pub fn dup2(oldfd: RawFd, newfd: RawFd) -> io::Result<RawFd> {
    // SAFETY: two ints. If `oldfd` is invalid the call fails with EBADF. If
    // `newfd` is already open, the kernel closes it atomically — there is no
    // window in which the supervisor has neither.
    if unsafe { libc::dup2(oldfd, newfd) } < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(newfd)
    }
}

/// `dup3(2)`: [`dup2`] that can also set `FD_CLOEXEC` atomically.
///
/// `dup2` has no "and set CLOEXEC" mode, and doing `dup2` then `fcntl` is a
/// race: a concurrent `fork` in the gap would inherit the fd without the flag.
/// An init forks constantly, so the race is not theoretical.
#[cfg(any(
    target_os = "linux",
    target_os = "android",
    target_os = "freebsd",
    target_os = "netbsd",
    target_os = "openbsd"
))]
pub fn dup3(oldfd: RawFd, newfd: RawFd, cloexec: bool) -> io::Result<RawFd> {
    let flags = if cloexec { libc::O_CLOEXEC } else { 0 };
    // SAFETY: three ints. `dup3` returns EINVAL rather than clobbering when
    // `oldfd == newfd`, so the "unconditional overwrite" contract of dup2 is
    // not silently violated.
    if unsafe { libc::dup3(oldfd, newfd, flags) } < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(newfd)
    }
}

/// `dup3(2)` for platforms that do not have it (OpenBSD < 5.9, older Apple).
///
/// Documented as a *degradation*: without `dup3` there is a theoretical window
/// between the `dup2` and the `fcntl`, so `cloexec: true` is only honoured for
/// fds that were not created by a concurrent `fork`. In a supervisor that
/// blocks signals and forks from a single thread, the window is not reachable.
#[cfg(not(any(
    target_os = "linux",
    target_os = "android",
    target_os = "freebsd",
    target_os = "netbsd",
    target_os = "openbsd"
)))]
pub fn dup3(oldfd: RawFd, newfd: RawFd, cloexec: bool) -> io::Result<RawFd> {
    let fd = dup2(oldfd, newfd)?;
    if cloexec {
        set_cloexec(newfd, true)?;
    }
    Ok(fd)
}

/// `fcntl(F_SETFD, FD_CLOEXEC)` — mark a descriptor close-on-exec.
pub fn set_cloexec(fd: RawFd, on: bool) -> io::Result<()> {
    // SAFETY: `fcntl` is variadic; the argument for F_SETFD is an int, and
    // passing it as such through the varargs is what the ABI expects.
    let rc = unsafe { libc::fcntl(fd, libc::F_SETFD, if on { libc::FD_CLOEXEC } else { 0 }) };
    if rc == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// Read a descriptor's `FD_CLOEXEC` flag.
pub fn get_cloexec(fd: RawFd) -> io::Result<bool> {
    // SAFETY: as above, for F_GETFD which takes no argument.
    let rc = unsafe { libc::fcntl(fd, libc::F_GETFD) };
    if rc < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(rc & libc::FD_CLOEXEC != 0)
    }
}

/// `pipe2(2)`, always creating both ends with `O_CLOEXEC`.
///
/// Why always CLOEXEC: `DESIGN.md` §9 requires that a service inherits
/// exactly the fds it was given and nothing else. A supervisor that forgets
/// `FD_CLOEXEC` on one pipe leaks a writable pipe into every service it ever
/// starts, and a service that writes to it corrupts the supervisor's own
/// control channel. Making it the *only* behaviour of this function removes
/// the possibility of forgetting.
///
/// Use [`set_nonblocking`] on the read end afterwards if the pipe is going
/// into the reactor; the reactor is level-triggered and assumes non-blocking
/// descriptors.
#[cfg(any(
    target_os = "linux",
    target_os = "android",
    target_os = "freebsd",
    target_os = "netbsd",
    target_os = "openbsd",
    target_os = "dragonfly"
))]
pub fn pipe2(cloexec: bool) -> io::Result<(RawFd, RawFd)> {
    let flags = if cloexec { libc::O_CLOEXEC } else { 0 };
    let mut fds = [0 as RawFd; 2];
    // SAFETY: `fds` is a live, correctly aligned array of exactly two ints,
    // which is what pipe2 writes. On failure it is untouched.
    if unsafe { libc::pipe2(fds.as_mut_ptr(), flags) } == 0 {
        Ok((fds[0], fds[1]))
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `pipe(2)` plus an explicit `FD_CLOEXEC` loop, for platforms without
/// `pipe2`.
///
/// Degradation: the flag is set after the pipe exists, so a concurrent `fork`
/// in that window inherits both ends. Single-threaded supervisors — the only
/// kind this project builds — cannot hit it.
#[cfg(not(any(
    target_os = "linux",
    target_os = "android",
    target_os = "freebsd",
    target_os = "netbsd",
    target_os = "openbsd",
    target_os = "dragonfly"
)))]
pub fn pipe2(cloexec: bool) -> io::Result<(RawFd, RawFd)> {
    let mut fds = [0 as RawFd; 2];
    // SAFETY: `fds` is a live array of two ints, exactly what pipe writes.
    if unsafe { libc::pipe(fds.as_mut_ptr()) } != 0 {
        return Err(io::Error::last_os_error());
    }
    if cloexec {
        for fd in fds {
            if let Err(e) = set_cloexec(fd, true) {
                let _ = close(fds[0]);
                let _ = close(fds[1]);
                return Err(e);
            }
        }
    }
    Ok((fds[0], fds[1]))
}

/// `O_NONBLOCK` on a descriptor.
///
/// Every fd handed to the reactor must be non-blocking: the reactor reports
/// *level* readiness (see [`crate::reactor`]), and a blocking descriptor in a
/// level-triggered loop is a deadlock.
pub fn set_nonblocking(fd: RawFd, on: bool) -> io::Result<()> {
    // Read the current flags and write them back with only `O_NONBLOCK`
    // changed.
    //
    // `F_SETFL` *replaces* the whole word, so passing a bare
    // `O_NONBLOCK` silently clears every other descriptor flag — including
    // `O_CLOEXEC`, which is the one that matters most. A descriptor marked
    // non-blocking and then made inheritable leaks into every `exec` the
    // process ever does, which is exactly the bug the exec-error pipe depends
    // on closing.
    //
    // SAFETY: `F_GETFL` returns the flag word in the int `out` points at; it
    // takes no descriptor state by reference. The pointer is a live local.
    let mut current: libc::c_int = 0;
    if unsafe { libc::fcntl(fd, libc::F_GETFL, &raw mut current) } == -1 {
        return Err(io::Error::last_os_error());
    }
    let updated = if on {
        current | libc::O_NONBLOCK
    } else {
        current & !libc::O_NONBLOCK
    };
    // SAFETY: `F_SETFL` takes the flag word as an int argument, passed as
    // such. `current` was populated by the `F_GETFL` above.
    if unsafe { libc::fcntl(fd, libc::F_SETFL, updated) } == -1 {
        return Err(io::Error::last_os_error());
    }
    Ok(())
}

/// `socketpair(2)`, both ends `O_CLOEXEC` and `SOCK_NONBLOCK`.
///
/// Used by tests and by the readiness handshake: a socket pair gives a
/// connection with a clean half-close (`shutdown`), which a pipe cannot.
pub fn socketpair() -> io::Result<(RawFd, RawFd)> {
    let mut fds = [0 as RawFd; 2];
    let flags = libc::SOCK_STREAM | socket_flags();
    // SAFETY: `fds` is a live array of two ints; `socketpair` writes exactly
    // two. The domain is AF_UNIX, which every platform in scope supports.
    if unsafe { libc::socketpair(libc::AF_UNIX, flags, 0, fds.as_mut_ptr()) } != 0 {
        return Err(io::Error::last_os_error());
    }
    for fd in fds {
        if let Err(e) = finish_socket_fd(fd) {
            let _ = close_quietly(fds[0]);
            let _ = close_quietly(fds[1]);
            return Err(e);
        }
    }
    Ok((fds[0], fds[1]))
}

/// The type bits to pass to `socket`/`socketpair`, so the descriptor comes out
/// close-on-exec and non-blocking.
///
/// Linux and the BSDs accept `SOCK_CLOEXEC | SOCK_NONBLOCK` as creation
/// flags, atomically. Darwin defines neither, so there the call is made plain
/// and finished afterwards with [`finish_socket_fd`]. Both spellings end in
/// the same place, so no caller has to know which one it is on.
#[cfg(any(
    target_os = "linux",
    target_os = "android",
    target_os = "freebsd",
    target_os = "netbsd",
    target_os = "openbsd",
    target_os = "dragonfly"
))]
const fn socket_flags() -> libc::c_int {
    libc::SOCK_CLOEXEC | libc::SOCK_NONBLOCK
}

/// Darwin has neither creation flag, so the call is made plain.
#[cfg(target_vendor = "apple")]
const fn socket_flags() -> libc::c_int {
    0
}

/// `recvmsg(2)` flags, with `MSG_CMSG_CLOEXEC` where the platform has it.
///
/// Linux, the BSDs and DragonFly define it, and there the received descriptor
/// is close-on-exec *at the kernel level*. Darwin does not have it, and there
/// the flag is set with an `fcntl` immediately after — the same documented
/// race as [`accept4_nocloexec`], for the same reason.
#[cfg(not(target_vendor = "apple"))]
const fn recv_flags() -> libc::c_int {
    libc::MSG_CMSG_CLOEXEC
}

/// Darwin has no `MSG_CMSG_CLOEXEC`.
#[cfg(target_vendor = "apple")]
const fn recv_flags() -> libc::c_int {
    0
}

/// Apply close-on-exec and non-blocking to a socket that was created without
/// the atomic creation flags.
///
/// Runs unconditionally, so the Darwin path and the rest of the crate are the
/// same code. The cost is two `fcntl`s on a non-Darwin machine, on sockets
/// that are created a handful of times per boot.
fn finish_socket_fd(fd: RawFd) -> io::Result<()> {
    set_cloexec(fd, true)?;
    set_nonblocking(fd, true)?;
    Ok(())
}

