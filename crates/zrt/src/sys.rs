/// `SOCK_STREAM | SOCK_CLOEXEC` on `AF_UNIX`.
pub fn socket_unix_stream() -> io::Result<RawFd> {
    socket_unix(libc::SOCK_STREAM)
}

/// `SOCK_DGRAM | SOCK_CLOEXEC` on `AF_UNIX`.
pub fn socket_unix_dgram() -> io::Result<RawFd> {
    socket_unix(libc::SOCK_DGRAM)
}

fn socket_unix(kind: libc::c_int) -> io::Result<RawFd> {
    // SAFETY: `socket` takes three ints; AF_UNIX with SOCK_STREAM or
    // SOCK_DGRAM and protocol 0 is the canonical portable form.
    let fd = unsafe { libc::socket(libc::AF_UNIX, kind | socket_flags(), 0) };
    if fd < 0 {
        return Err(io::Error::last_os_error());
    }
    match finish_socket_fd(fd) {
        Ok(()) => Ok(fd),
        Err(e) => {
            // The descriptor exists and would otherwise leak for the rest of
            // the process — in a supervisor, the difference between a failed
            // call and a mystery fd three services later.
            let _ = close_quietly(fd);
            Err(e)
        }
    }
}

/// `bind(2)` for a `AF_UNIX` socket.
///
/// A path starting with `@` binds in the Linux **abstract** namespace (byte 0
/// of `sun_path`, no filesystem entry, no cleanup, survives a full `/run`
/// remount). Every other path is a real filesystem path, which is what the BSD
/// builds use and what the config format can therefore rely on.
///
/// `sun_path` is 108 bytes on Linux and 104 on the BSDs; a longer path is
/// rejected locally with `InvalidInput` rather than truncated, because a
/// truncated socket path is a socket nobody else can find.
pub fn bind_unix(fd: RawFd, path: &Path) -> io::Result<()> {
    let bytes = path.as_os_str().as_bytes();
    let (abstract_ns, tail) = match bytes.split_first() {
        Some((b'@', rest)) => (true, rest),
        _ => (false, bytes),
    };
    if tail.contains(&0) {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "unix socket path contains an interior NUL",
        ));
    }
    let mut addr: libc::sockaddr_un = unsafe { core::mem::zeroed() };
    addr.sun_family = libc::AF_UNIX as libc::sa_family_t;
    let cap = addr.sun_path.len();
    if tail.len() >= cap {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!(
                "unix socket path is {} bytes; sun_path holds {}",
                tail.len(),
                cap - 1
            ),
        ));
    }
    if abstract_ns {
        // Leave sun_path[0] as NUL; that is precisely what makes it abstract.
        for (i, b) in tail.iter().enumerate() {
            addr.sun_path[i + 1] = *b as libc::c_char;
        }
    } else {
        for (i, b) in tail.iter().enumerate() {
            addr.sun_path[i] = *b as libc::c_char;
        }
        // NUL terminate: `addr` is zeroed, and the check above guarantees
        // there is room for the terminator.
    }
    // SAFETY: `addr` is a live, correctly aligned `sockaddr_un` with
    // sun_family set and a NUL-terminated (or abstract) path; the length
    // passed is the real length, not `size_of`, because the kernel reads
    // `sun_path` up to the first NUL and the abstract form has none.
    // Both spellings of the length happen to be `tail.len() + 1`, and that is
    // not a coincidence: the abstract form's leading NUL *is* the first byte
    // of the path. They are written as one expression because a reader who
    // thinks the two lengths differ will start "fixing" this.
    let len = std::mem::size_of::<libc::sa_family_t>() + tail.len() + 1;
    if unsafe {
        libc::bind(
            fd,
            (&raw const addr).cast::<libc::sockaddr>(),
            len as libc::socklen_t,
        )
    } != 0
    {
        return Err(io::Error::last_os_error());
    }
    Ok(())
}

/// `listen(2)`.
pub fn listen(fd: RawFd, backlog: i32) -> io::Result<()> {
    // SAFETY: an int and an int. A negative backlog is rejected by the kernel.
    if unsafe { libc::listen(fd, backlog) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `accept4(2)` with `SOCK_CLOEXEC`, retrying `EINTR`.
///
/// `EAGAIN` is returned to the caller unchanged: on a non-blocking listening
/// socket it is the normal "nothing yet" answer, and the event loop is
/// structured to treat it as such.
#[cfg(any(
    target_os = "linux",
    target_os = "android",
    target_os = "freebsd",
    target_os = "netbsd",
    target_os = "openbsd",
    target_os = "dragonfly"
))]
pub fn accept4_nocloexec(fd: RawFd) -> io::Result<RawFd> {
    loop {
        // SAFETY: `accept4` writes the new descriptor through its return
        // value only; no out-pointers, so there is nothing to get wrong here.
        let conn = unsafe {
            libc::accept4(
                fd,
                std::ptr::null_mut(),
                std::ptr::null_mut(),
                libc::SOCK_CLOEXEC,
            )
        };
        if conn >= 0 {
            return Ok(conn);
        }
        let err = io::Error::last_os_error();
        if err.kind() != io::ErrorKind::Interrupted {
            return Err(err);
        }
    }
}

/// `accept4_nocloexec` where `accept4(2)` does not exist.
///
/// Darwin is the case in scope. The flag is applied with `fcntl` immediately
/// afterwards, which is a race in a program that forks concurrently — the
/// whole reason `accept4` exists. zinit's supervisor is single-threaded and
/// forks only from its event loop, so the window is not reachable; it is
/// documented rather than pretended away.
#[cfg(target_vendor = "apple")]
pub fn accept4_nocloexec(fd: RawFd) -> io::Result<RawFd> {
    loop {
        // SAFETY: null out-pointers are explicitly allowed by `accept(2)`, and
        // the return value is the only thing written.
        let conn = unsafe { libc::accept(fd, std::ptr::null_mut(), std::ptr::null_mut()) };
        if conn >= 0 {
            return match set_cloexec(conn, true) {
                Ok(()) => Ok(conn),
                Err(e) => {
                    let _ = close_quietly(conn);
                    Err(e)
                }
            };
        }
        let err = io::Error::last_os_error();
        if err.kind() != io::ErrorKind::Interrupted {
            return Err(err);
        }
    }
}

/// Send one byte of payload plus one file descriptor over a unix socket
/// (`SCM_RIGHTS`).
///
/// This is how the supervisor hands a service its log fd or its notify fd
/// *without* letting it inherit anything else: one syscall, one fd, and the
/// receiving side gets exactly what was sent. The alternative — arranging fd
/// numbers in advance so the child inherits them — is the thing `FD_CLOEXEC`
/// exists to prevent.
///
/// Returns the number of payload bytes written, which is 0 or 1; a large
/// payload is truncated, and that is the caller's business.
pub fn send_fd(sock: RawFd, payload: &[u8], fd: RawFd) -> io::Result<usize> {
    let mut byte = [payload.first().copied().unwrap_or(0u8)];
    let mut iov = libc::iovec {
        iov_base: byte.as_mut_ptr().cast::<libc::c_void>(),
        iov_len: byte.len(),
    };
    // One control message carrying exactly one fd. The layout is computed by
    // hand rather than with the CMSG_* macros because those differ across
    // platforms in both availability and signature, and this file is the one
    // place where a mistake is a memory-safety bug.
    //
    // `CMSG_LEN`-equivalent: header + the data word, both rounded up to the
    // control buffer's alignment. `cmsg_len` and `msg_controllen` are `size_t`
    // on Linux and `u32` (`socklen_t`) on the BSDs, which is why every
    // assignment here goes through `as _` — the target type is inferred from
    // the field and no cast can be wrong for the platform it is compiled on.
    let hdr_size = hdr_size_of::<libc::cmsghdr>();
    let data_len = cmsg_align(len_of::<RawFd>());
    let space = hdr_size + data_len;
    let mut cmsg_buf = [0u8; 64];
    if space > cmsg_buf.len() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "SCM_RIGHTS control buffer too small",
        ));
    }
    {
        // SAFETY: `cmsg_buf` is a live `[u8; 64]` with alignment 1; the
        // `cmsghdr` written into it is 8-aligned by construction (64 is a
        // multiple of 8), which is what the kernel requires of a control
        // message. The write stays within `hdr_size`.
        let hdr = cmsg_buf.as_mut_ptr().cast::<libc::cmsghdr>();
        unsafe {
            core::ptr::write_bytes(hdr, 0, 1);
            (*hdr).cmsg_len = (hdr_size + cmsg_align(size_of::<libc::c_int>())) as _;
            (*hdr).cmsg_level = libc::SOL_SOCKET;
            (*hdr).cmsg_type = libc::SCM_RIGHTS;
        }
        // SAFETY: the data word starts at `hdr_size`, is 4-byte aligned, and
        // `space` covers hdr_size + align(sizeof(c_int)) = 8 + 4 + 4 = 16.
        let data = unsafe { cmsg_buf.as_mut_ptr().add(hdr_size).cast::<libc::c_int>() };
        unsafe { core::ptr::write(data, fd) };
    }
    let mut msg: libc::msghdr = unsafe { core::mem::zeroed() };
    msg.msg_iov = &raw mut iov;
    msg.msg_iovlen = 1;
    msg.msg_control = cmsg_buf.as_mut_ptr().cast::<libc::c_void>();
    msg.msg_controllen = (hdr_size + data_len) as _;
    let _ = space;
    // SAFETY: `iov`/`msg` are live and correctly aligned; `msg_iovlen` matches
    // the one-element array; `msg_control` points at a buffer of exactly
    // `msg_controllen` bytes holding one well-formed SCM_RIGHTS message.
    let sent = unsafe { libc::sendmsg(sock, &raw const msg, libc::MSG_NOSIGNAL) };
    if sent < 0 {
        return Err(io::Error::last_os_error());
    }
    Ok(sent as usize)
}

/// Receive up to one payload byte plus at most one file descriptor.
pub fn recv_fd(sock: RawFd) -> io::Result<(u8, Option<RawFd>)> {
    let mut byte = [0u8; 1];
    let mut iov = libc::iovec {
        iov_base: byte.as_mut_ptr().cast::<libc::c_void>(),
        iov_len: 1,
    };
    let mut cmsg_buf = [0u8; 64];
    let mut msg: libc::msghdr = unsafe { core::mem::zeroed() };
    msg.msg_iov = &raw mut iov;
    msg.msg_iovlen = 1;
    msg.msg_control = cmsg_buf.as_mut_ptr().cast::<libc::c_void>();
    msg.msg_controllen = cmsg_buf.len() as _;
    // SAFETY: both buffers are live with their exact lengths recorded in
    // `msg`; `recvmsg` will not write past `msg_controllen` in `msg_control`
    // or `msg_iovlen` in the iovec. Where `MSG_CMSG_CLOEXEC` exists the
    // received descriptor is close-on-exec *at the kernel level*.
    let got = unsafe { libc::recvmsg(sock, &raw mut msg, recv_flags()) };
    if got < 0 {
        return Err(io::Error::last_os_error());
    }
    let mut out_fd: Option<RawFd> = None;
    if msg.msg_controllen as usize >= hdr_size_of::<libc::cmsghdr>() {
        // SAFETY: the kernel wrote a control message into `cmsg_buf` and
        // reported its length in `msg_controllen`, which is checked above.
        // Iterating with CMSG_FIRSTHDR/CMSG_NXTHDR is the only legal way to
        // walk it; both are pure pointer arithmetic over the kernel-written
        // buffer.
        unsafe {
            let mut cmsg = libc::CMSG_FIRSTHDR(&raw const msg);
            while !cmsg.is_null() {
                if (*cmsg).cmsg_level == libc::SOL_SOCKET && (*cmsg).cmsg_type == libc::SCM_RIGHTS {
                    let data = libc::CMSG_DATA(cmsg);
                    out_fd = Some(core::ptr::read(data.cast::<libc::c_int>()));
                    break;
                }
                cmsg = libc::CMSG_NXTHDR(&raw const msg, cmsg);
            }
        }
    }
    let out_fd = match out_fd {
        Some(f) => match set_cloexec(f, true) {
            // On Linux and the BSDs `MSG_CMSG_CLOEXEC` already did this and
            // the `fcntl` merely confirms it; on Darwin it is the only thing
            // making it true.
            Ok(()) => Some(f),
            Err(e) => {
                let _ = close_quietly(f);
                return Err(e);
            }
        },
        None => None,
    };
    Ok((byte[0], out_fd))
}

