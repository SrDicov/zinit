/// `read(2)` on a raw descriptor, retrying `EINTR`.
///
/// This crate is fd-centric by design — descriptors are what the reactor, the
/// signal source and the child tracker all speak — so `std::io::Read` on a
/// `File` is a second, incompatible vocabulary. This is the small bridge: same
/// errno, same `EINTR` policy, no allocation and no `BufReader` state that a
/// forked child would duplicate.
///
/// `Ok(0)` means end of file, which is *data*, not an error. In a supervisor
/// that distinction is load-bearing: a closed notify pipe is how a service
/// says "I am done", and it arrives as a zero-length read.
pub fn read(fd: RawFd, buf: &mut [u8]) -> io::Result<usize> {
    if buf.is_empty() {
        return Ok(0);
    }
    loop {
        // SAFETY: `buf` is a live, uniquely borrowed slice and `read` is told
        // its exact length; the kernel writes at most that many bytes and
        // retains no pointer.
        let n = unsafe { libc::read(fd, buf.as_mut_ptr().cast::<libc::c_void>(), buf.len()) };
        if n >= 0 {
            return Ok(n as usize);
        }
        let err = io::Error::last_os_error();
        if err.kind() != io::ErrorKind::Interrupted {
            return Err(err);
        }
    }
}

/// `write(2)` on a raw descriptor, retrying `EINTR`.
///
/// A short write is reported as-is rather than looped. Looping would hide a
/// partially written log line or a partially sent control frame, and both of
/// those are decisions the *caller* has to make: this layer does not know
/// whether a half-written frame is retryable.
pub fn write(fd: RawFd, buf: &[u8]) -> io::Result<usize> {
    if buf.is_empty() {
        return Ok(0);
    }
    loop {
        // SAFETY: `buf` is a live, immutable slice and `write` is told its
        // exact length; the kernel only reads it.
        let n = unsafe { libc::write(fd, buf.as_ptr().cast::<libc::c_void>(), buf.len()) };
        if n >= 0 {
            return Ok(n as usize);
        }
        let err = io::Error::last_os_error();
        if err.kind() != io::ErrorKind::Interrupted {
            return Err(err);
        }
    }
}

