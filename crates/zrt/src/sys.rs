/// The four ids that define who a process currently is.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Ids {
    /// Real user id.
    pub uid: u32,
    /// Effective user id.
    pub euid: u32,
    /// Real group id.
    pub gid: u32,
    /// Effective group id.
    pub egid: u32,
}

/// Read the current real and effective ids.
///
/// Taken as a group so that the drop of privileges can be *verified* against
/// all four at once. Rule 2 in `DESIGN.md` §9: releasing privilege is not
/// believed, it is checked.
pub fn ids() -> Ids {
    // SAFETY: four getters with no arguments and no preconditions; they cannot
    // fail. `geteuid` is a real syscall, not a cached value, which is what
    // makes the post-drop verification meaningful.
    unsafe {
        Ids {
            uid: libc::getuid() as u32,
            euid: libc::geteuid() as u32,
            gid: libc::getgid() as u32,
            egid: libc::getegid() as u32,
        }
    }
}

/// `setresuid(uid, euid, suid)` — set all three user ids atomically.
///
/// Linux only. The atomic three-argument form exists precisely so that a
/// privileged process cannot be caught between two `setuid` calls with a
/// window in which it can regain privilege (`DESIGN.md` §9 rule 1). BSDs have
/// no such call; there, [`setuid_checked`] is the honest fallback.
#[cfg(any(target_os = "linux", target_os = "android"))]
pub fn setresuid(uid: u32, euid: u32, suid: u32) -> io::Result<()> {
    // SAFETY: three ints, no pointers. Failure leaves the ids unchanged.
    if unsafe { libc::setresuid(uid, euid, suid) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `setresgid(gid, egid, sgid)`. Linux only; see [`setresuid`].
#[cfg(any(target_os = "linux", target_os = "android"))]
pub fn setresgid(gid: u32, egid: u32, sgid: u32) -> io::Result<()> {
    // SAFETY: three ints, no pointers.
    if unsafe { libc::setresgid(gid, egid, sgid) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `setgroups(0, NULL)` — drop every supplementary group.
///
/// The first step of the drop, before either uid or gid is touched, because
/// supplementary groups are the easiest privilege to forget and the one that
/// survives a careless `setuid`.
pub fn setgroups_empty() -> io::Result<()> {
    // SAFETY: a null pointer with a count of zero is the documented way to
    // ask for "no groups"; the kernel checks the count and never dereferences.
    if unsafe { libc::setgroups(0, std::ptr::null()) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `setuid(uid)` — the portable fallback, followed by a verification.
///
/// On a platform without `setresuid` this is the *only* option, and on some
/// of them it has the well-known behaviour of also changing the saved id.
/// That is why the result is checked with [`ids`] instead of assumed, and why
/// the failure is a hard error: a service that silently kept root is worse
/// than a service that refused to start.
pub fn setuid_checked(uid: u32) -> io::Result<()> {
    // SAFETY: one int, no pointers.
    if unsafe { libc::setuid(uid) } != 0 {
        return Err(io::Error::last_os_error());
    }
    verify_dropped(uid)
}

/// `setgid(gid)`, with the same verification rationale as [`setuid_checked`].
pub fn setgid_checked(gid: u32) -> io::Result<()> {
    // SAFETY: one int, no pointers.
    if unsafe { libc::setgid(gid) } != 0 {
        return Err(io::Error::last_os_error());
    }
    let now = ids();
    if now.gid != gid || now.egid != gid {
        return Err(io::Error::new(
            io::ErrorKind::PermissionDenied,
            format!(
                "setgid({gid}) did not take: gid={} egid={}",
                now.gid, now.egid
            ),
        ));
    }
    Ok(())
}

/// Assert that the real and effective user ids are both `uid`.
///
/// This is the check `DESIGN.md` §9 rule 2 asks for. It is a separate function
/// so that the `setresuid` path can verify too — the kernel can fail to set
/// what it was asked to set under some LSM configurations, and "asked" is not
/// "done".
pub fn verify_dropped(uid: u32) -> io::Result<()> {
    let now = ids();
    if now.uid != uid || now.euid != uid {
        return Err(io::Error::new(
            io::ErrorKind::PermissionDenied,
            format!(
                "uid drop failed: wanted {uid}, uid={} euid={}",
                now.uid, now.euid
            ),
        ));
    }
    Ok(())
}

/// `prctl(PR_SET_NO_NEW_PRIVS, 1)` — forbid gaining privilege via exec.
///
/// Linux only, and the single most valuable line in the whole drop sequence:
/// after it, a setuid binary a service execs cannot raise that service's
/// privilege. Not a substitute for the uid change, but it makes a mistake in
/// the uid change non-exploitable.
#[cfg(any(target_os = "linux", target_os = "android"))]
pub fn set_no_new_privs() -> io::Result<()> {
    // SAFETY: prctl with PR_SET_NO_NEW_PRIVS takes two int-like arguments;
    // the constant and the value are both compile-time.
    if unsafe { libc::prctl(libc::PR_SET_NO_NEW_PRIVS, 1, 0, 0, 0) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `PER_LINUX`, from `linux/personality.h`.
///
/// Not re-exported by the `libc` crate, and hand-written rather than copied
/// from a header at build time: this crate has no build script and no
/// `pkg-config`, and one more `const` is a smaller price than either.
#[cfg(any(target_os = "linux", target_os = "android"))]
const PER_LINUX: libc::c_ulong = 0x0000;

/// `personality(ADDR_NO_RANDOMIZE | PER_LINUX)` — disable ASLR for a service.
///
/// Linux only. Queried rather than set on purpose: this is a probe, and a
/// probe must have no side effects. An invalid persona (`0xffff_ffff`) makes
/// the kernel answer with the current value and change nothing.
#[cfg(any(target_os = "linux", target_os = "android"))]
pub fn query_personality() -> io::Result<u32> {
    // SAFETY: `personality` takes and returns a persona bitmask; the invalid
    // value is documented to be a pure query that changes nothing.
    let rc = unsafe { libc::personality(!0u32 as libc::c_ulong) };
    if rc == -1 {
        // The kernel answers -1/EINVAL for an unknown persona, so `EINVAL`
        // means "the call exists" and anything else is a real failure.
        let e = io::Error::last_os_error();
        if e.raw_os_error() == Some(libc::EINVAL) {
            return Ok(0);
        }
        return Err(e);
    }
    Ok(rc as u32)
}

/// `personality(PER_LINUX | ADDR_NO_RANDOMIZE)`. Linux only.
#[cfg(any(target_os = "linux", target_os = "android"))]
pub fn set_addr_no_randomize() -> io::Result<()> {
    let want = PER_LINUX | libc::ADDR_NO_RANDOMIZE as libc::c_ulong;
    // SAFETY: one ulong; the kernel validates the persona and returns the
    // previous one.
    if unsafe { libc::personality(want) } == -1 {
        return Err(io::Error::last_os_error());
    }
    Ok(())
}

/// `pidfd_open(2)`: an fd that becomes readable when that exact process dies.
///
/// Linux 5.3+. The value of this call is not "an event when a pid exits" —
///
/// that is what `SIGCHLD` already does — but that the fd refers to *one
/// specific process*. A pid can be recycled the instant it dies; a pidfd
/// cannot. An init that learns "child 1234 died" and then looks up 1234 in a
/// table has a race, and the pidfd backend closes it.
///
/// Routed through `syscall(2)` rather than the libc wrapper because glibc only
/// grew the wrapper in 2.36, and zinit has to run on the glibc of whatever
/// distribution booted it.
#[cfg(any(target_os = "linux", target_os = "android"))]
pub fn pidfd_open(pid: i32) -> io::Result<RawFd> {
    // SAFETY: variadic `syscall` with two integer arguments passed as
    // `c_long`, which is what the kernel's `sys_pidfd_open(pid, flags)`
    // prototype expects. The return value is an fd or -1 with errno set.
    // (x32 is excluded from the capabilities probe for the same reason: a
    // variadic pointer/argument width mismatch. This call passes no
    // pointers, so it is safe there too.)
    let rc = unsafe { libc::syscall(libc::SYS_pidfd_open, pid as libc::c_long, 0 as libc::c_long) };
    if rc < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(rc as RawFd)
    }
}

