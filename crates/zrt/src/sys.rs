/// `open(2)` with `O_CLOEXEC` always set.
///
/// There is no way to get a non-CLOEXEC fd from this module on purpose. The
/// only descriptors that must survive an exec are the ones stdio and the
/// control protocol hold, and those are duplicated with [`dup2`]/[`dup3`]
/// explicitly.
pub fn open_cloexec(path: &Path, flags: i32, mode: u32) -> io::Result<RawFd> {
    openat_nofollow(libc::AT_FDCWD, path, flags, mode)
}

/// `openat(2)` with `O_NOFOLLOW` and `O_CLOEXEC` always set.
///
/// `O_NOFOLLOW` because the supervisor's whole security argument rests on not
/// being tricked by a symlink at a path it is about to chown, chmod or mount
/// (`DESIGN.md` §9 rule 4). `O_CLOEXEC` for the leak reason in [`pipe2`].
///
/// Pass `AT_FDCWD` as `dirfd` for an absolute path; this exists so a caller
/// can open relative to a directory fd it already holds, which closes the
/// TOCTOU window that `open(path)` + `fchown(path)` leaves open.
pub fn openat_nofollow(dirfd: RawFd, path: &Path, flags: i32, mode: u32) -> io::Result<RawFd> {
    let c = cpath(path)?;
    let flags = flags | libc::O_NOFOLLOW | libc::O_CLOEXEC;
    // SAFETY: `c` is a NUL-terminated string alive for this call, `dirfd` is
    // either AT_FDCWD or a real descriptor the caller owns, and `mode` is only
    // consulted when O_CREAT is set. The kernel copies the path; it does not
    // retain the pointer.
    let fd = unsafe { libc::openat(dirfd, c.as_ptr(), flags, mode as libc::c_uint) };
    if fd < 0 {
        Err(io::Error::last_os_error())
    } else {
        Ok(fd)
    }
}

/// `fchown(2)` on an **open descriptor**.
///
/// Only ever on an fd, never on a path: chowning by name is a TOCTOU race
/// where the file can be swapped for a symlink between the check and the
/// call. That is rule 4 in `DESIGN.md` §9 and it is not negotiable.
pub fn fchown(fd: RawFd, uid: u32, gid: u32) -> io::Result<()> {
    // SAFETY: three ints, no pointers. The descriptor must be open; a stale
    // one returns EBADF, which is exactly the signal we want.
    if unsafe { libc::fchown(fd, uid, gid) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `fchmod(2)` on an open descriptor. Same TOCTOU argument as [`fchown`].
pub fn fchmod(fd: RawFd, mode: u32) -> io::Result<()> {
    // SAFETY: two ints, no pointers.
    if unsafe { libc::fchmod(fd, mode as libc::mode_t) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `mkdir(2)` for a single component, without following a trailing symlink.
pub fn mkdir(path: &Path, mode: u32) -> io::Result<()> {
    let c = cpath(path)?;
    // SAFETY: `c` is NUL-terminated and alive for the call; `mode` is only
    // used by this very syscall.
    if unsafe { libc::mkdir(c.as_ptr(), mode as libc::mode_t) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `mkdir -p`: create every missing component, succeed if it already exists.
///
/// An existing component that is **not** a directory is `ENOTDIR` — a real
/// error, never ignored. Silently continuing there is how an init ends up
/// writing its socket into a file.
pub fn mkdir_p(path: &Path, mode: u32) -> io::Result<()> {
    let mut cur = PathBuf::new();
    for comp in path.components() {
        match comp {
            Component::RootDir => cur.push("/"),
            Component::CurDir => {}
            Component::ParentDir => {
                cur.pop();
            }
            Component::Prefix(_) | Component::Normal(_) => cur.push(comp.as_os_str()),
        }
        if cur.as_os_str().is_empty() {
            continue;
        }
        match mkdir(&cur, mode) {
            Ok(()) => {}
            Err(e) if e.raw_os_error() == Some(libc::EEXIST) => {
                // Already there. It must be a directory, or we are about to
                // create things *inside* a regular file.
                match stat_is_dir(&cur)? {
                    true => {}
                    false => {
                        return Err(io::Error::new(
                            io::ErrorKind::AlreadyExists,
                            format!("{} exists and is not a directory", cur.display()),
                        ));
                    }
                }
            }
            Err(e) if e.raw_os_error() == Some(libc::ENOENT) => {
                // A concurrent `mkdir -p` beat us to it, or a parent really is
                // missing because it is a dangling symlink. Either way the
                // recursive call from the next component is the fix, and if
                // there is no next component this is the genuine error.
                return Err(e);
            }
            Err(e) => return Err(e),
        }
    }
    Ok(())
}

/// Whether `path` exists and is a directory.
pub fn stat_is_dir(path: &Path) -> io::Result<bool> {
    let c = cpath(path)?;
    let mut st: libc::stat = unsafe { core::mem::zeroed() };
    // SAFETY: `st` is a live, aligned `stat` of the size libc's `stat` type
    // describes, and `lstat` writes exactly one. `c` is NUL-terminated.
    if unsafe { libc::lstat(c.as_ptr(), &raw mut st) } != 0 {
        return Err(io::Error::last_os_error());
    }
    Ok(st.st_mode & libc::S_IFMT == libc::S_IFDIR)
}

/// `(device, inode)` of an existing path.
///
/// Used to detect that a pidfile or a socket belongs to *this* boot and
/// *this* filesystem — a stale `/run` file from the previous run must not be
/// mistaken for a live one. Reports the target of a symlink, deliberately:
/// the question is "what does this path resolve to", and a dangling symlink
/// is an error here, not a special case.
pub fn stat_dev_ino(path: &Path) -> io::Result<(u64, u64)> {
    let c = cpath(path)?;
    let mut st: libc::stat = unsafe { core::mem::zeroed() };
    // SAFETY: as `stat_is_dir`, with `stat` instead of `lstat`.
    if unsafe { libc::stat(c.as_ptr(), &raw mut st) } != 0 {
        return Err(io::Error::last_os_error());
    }
    Ok((st.st_dev as u64, st.st_ino as u64))
}

/// `readlink(2)` into an owned `PathBuf`.
///
/// A symlink whose target is longer than 255 bytes comes back as
/// `ENAMETOOLONG` from a fixed buffer, which is reported rather than
/// silently truncated. Init symlinks (`/run` → `/var/run`) are short; if one
/// ever is not, the operator should know rather than debug a truncated path.
pub fn readlink(path: &Path) -> io::Result<PathBuf> {
    let c = cpath(path)?;
    let mut buf = vec![0u8; 4096];
    // SAFETY: `buf` is a live allocation of exactly `buf.len()` bytes, which
    // is the size passed in `n`. `readlink` writes at most `n` bytes and does
    // not NUL-terminate, so the length is taken from the return value.
    let n = unsafe {
        libc::readlink(
            c.as_ptr(),
            buf.as_mut_ptr().cast::<libc::c_char>(),
            buf.len(),
        )
    };
    if n < 0 {
        return Err(io::Error::last_os_error());
    }
    let read = n as usize;
    if read == buf.len() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "symlink target longer than the 4096-byte readlink buffer",
        ));
    }
    buf.truncate(read);
    Ok(PathBuf::from(OsStr::from_bytes(&buf)))
}

/// `unlink(2)`.
pub fn unlink(path: &Path) -> io::Result<()> {
    let c = cpath(path)?;
    // SAFETY: NUL-terminated path, no other preconditions.
    if unsafe { libc::unlink(c.as_ptr()) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

/// `rename(2)`: atomic replace.
///
/// This is how a service's state file is published, and why it is `rename` and
/// not "write, then rename the temp": a reader either sees the whole old file
/// or the whole new one.
pub fn rename(from: &Path, to: &Path) -> io::Result<()> {
    let a = cpath(from)?;
    let b = cpath(to)?;
    // SAFETY: two NUL-terminated paths, both alive for the call.
    if unsafe { libc::rename(a.as_ptr(), b.as_ptr()) } == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

